#!/usr/bin/env python3
"""kb_derive.py — regenerate derived views from the knowledge log.

Usage:
    python scripts/kb_derive.py --kb KBDIR grades          # JSON grades to stdout
    python scripts/kb_derive.py --kb KBDIR current-state   # markdown view to stdout
                                                             (also written to kb/derived/)

Everything derived is regenerable and deterministic: same log in,
byte-identical view out. Derived artifacts are disposable; deleting
kb/derived/ and rebuilding loses nothing.

Grading rule (never upgrade past evidence):
- level          = highest level with ANY evidence (coached or not)
- unaided_level  = highest level with coached:false evidence, else null
- coached        = true when the node's top-level evidence was coached
- retention      = true only when the best unaided level came with delay_days > 0
                   (a retention claim requires real delay; delay is a
                   dimension, never folded into the level)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kb_lib import LEVELS, KBError, load_events


def compute_grades(events: list[dict]) -> dict:
    nodes: dict[str, list[dict]] = {}
    for event in events:
        if event.get("type") == "evidence":
            nodes.setdefault(event["node"], []).append(event)

    grades = {}
    for node in sorted(nodes):
        evs = nodes[node]
        best = max(evs, key=lambda e: (LEVELS.index(e["level"]), e.get("ts", "")))
        unaided = [e for e in evs if not e["coached"]]
        best_unaided = (
            max(unaided, key=lambda e: (LEVELS.index(e["level"]), e.get("ts", "")))
            if unaided
            else None
        )
        grades[node] = {
            "level": best["level"],
            "coached": bool(best["coached"]),
            "unaided_level": best_unaided["level"] if best_unaided else None,
            "retention": bool(best_unaided and best_unaided["delay_days"] > 0),
            "events": len(evs),
            "last_ts": max(e.get("ts", "") for e in evs),
        }
    return grades


def render_current_state(events: list[dict]) -> str:
    grades = compute_grades(events)
    statements = {}
    for event in events:
        if event.get("type") == "node_created":
            statements[event["node"]] = event.get("statement", "")

    lines = [
        "# Current State",
        "",
        "<!-- GENERATED by scripts/kb_derive.py from kb/events.jsonl — do not hand-edit. -->",
        "",
        "## Node grades",
        "",
    ]
    for node, grade in grades.items():
        lines.append(f"### {node}")
        if node in statements:
            lines.append(f"> {statements[node]}")
        retention = "retention win" if grade["retention"] else "no delayed evidence"
        unaided = grade["unaided_level"] or "none"
        coached = "coached" if grade["coached"] else "unaided"
        lines.append(
            f"- level: {grade['level']} ({coached}); unaided: {unaided}; "
            f"{retention}; events: {grade['events']}; last: {grade['last_ts']}"
        )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kb", required=True, type=Path, help="knowledge base directory")
    parser.add_argument("view", choices=["grades", "current-state"])
    args = parser.parse_args(argv)

    try:
        events = load_events(args.kb)
    except KBError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.view == "grades":
        print(json.dumps(compute_grades(events), indent=2, sort_keys=True))
    else:
        view = render_current_state(events)
        derived = args.kb / "derived"
        derived.mkdir(parents=True, exist_ok=True)
        (derived / "current-state.md").write_text(view, encoding="utf-8")
        print(view)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
